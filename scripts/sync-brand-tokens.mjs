import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const tokens = JSON.parse(await readFile(new URL('packages/pvp-ui/brand-tokens.json', root), 'utf8'));
const kebab = name => name.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
const colors = Object.entries(tokens.colors);
const css = ['/* Generated by scripts/sync-brand-tokens.mjs. Edit packages/pvp-ui/brand-tokens.json. */', ':root {',
  ...colors.map(([name, value]) => `  --pvp-${kebab(name)}: ${value};`),
  ...Object.entries(tokens.radius).map(([name, value]) => `  --pvp-radius-${name}: ${value}px;`),
  ...Object.entries(tokens.spacing).map(([name, value]) => `  --pvp-space-${name}: ${value}px;`),
  ...Object.entries(tokens.motion).map(([name, value]) => `  --pvp-${name}: ${value}ms;`), '}', ''].join('\n');
const dart = ['// Generated by scripts/sync-brand-tokens.mjs. Edit packages/pvp-ui/brand-tokens.json.', "import 'package:flutter/material.dart';", '', 'abstract final class PvpBrandColors {',
  ...colors.map(([name, value]) => `  static const ${name} = Color(0xff${value.slice(1)});`), '}', '',
  'abstract final class PvpBrandMotion {', ...Object.entries(tokens.motion).map(([name, value]) => `  static const ${name} = Duration(milliseconds: ${value});`), '}', ''].join('\n');
await Promise.all([writeFile(new URL('web/brand-tokens.css', root), css), writeFile(new URL('desktop/lib/ui/brand_tokens.dart', root), dart)]);
console.log('Updated PVP brand tokens for browser and Flutter.');
