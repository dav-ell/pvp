#!/usr/bin/env python3
"""Build both clients' icon bundles from the pinned, licensed SVG subset offline."""
from pathlib import Path
import json,re,shutil
root=Path(__file__).resolve().parents[1]
source=root/'packages/pvp-ui/icons'
assets=root/'desktop/assets/icons';assets.mkdir(parents=True,exist_ok=True)
symbols=[]
for svg in sorted(source.glob('*.svg')):
    content=re.search(r'<svg[^>]*>(.*)</svg>',svg.read_text(),re.S).group(1)
    symbols.append(f'<symbol id="{svg.stem}" viewBox="0 0 24 24">{content}</symbol>')
    shutil.copyfile(svg,assets/svg.name)
notice='<!-- PVP Lucide icon license\n'+(source/'LICENSE').read_text().replace('\n---\n','\n- - -\n')+'\n-->\n'
(root/'web/icons.svg').write_text(notice+'<svg xmlns="http://www.w3.org/2000/svg"><defs>'+''.join(symbols)+'</defs></svg>\n')
page=root/'web/index.html'
html=re.sub(r'<!-- PVP Lucide icon license\n.*?-->\n','',page.read_text(),flags=re.S)
page.write_text(html.replace('<svg class="icon-defs"',notice+'<svg class="icon-defs"',1))
shutil.copyfile(source/'LICENSE',assets/'LICENSE')
map=json.loads((root/'packages/pvp-ui/material-aliases.json').read_text())
(root/'desktop/lib/ui/icon_aliases.dart').write_text('// Generated by scripts/sync-ui-icons.py.\nimport "package:flutter/material.dart";\nfinal pvpIconAliases = <IconData,String>{\n'+''.join(f"  Icons.{k}: '{v}',\n" for k,v in map.items())+'};\n')
